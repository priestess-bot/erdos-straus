def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def divisors(value: int) -> list[int]:
    if value <= 0:
        raise ValueError("divisors requires a positive integer")
    result = [1]
    factor = 2
    remaining = value
    while factor * factor <= remaining:
        if remaining % factor:
            factor = 3 if factor == 2 else factor + 2
            continue
        exponent = 0
        while remaining % factor == 0:
            remaining //= factor
            exponent += 1
        result = [entry * factor**power for entry in result for power in range(exponent + 1)]
        factor = 3 if factor == 2 else factor + 2
    if remaining > 1:
        result = [entry * remaining for entry in result]
    return sorted(result)


def valuation(value: int, prime: int) -> int:
    count = 0
    while value % prime == 0:
        value //= prime
        count += 1
    return count


def admissible_gaps(modulus: int, prime: int) -> list[int]:
    return [
        value
        for value in divisors(modulus)
        if value % 4 == 3 and 3 <= value <= prime - 2
    ]


def strip_support(value: int, primes: list[int]) -> int:
    if value == 0:
        return 0
    for prime in primes:
        while value % prime == 0:
            value //= prime
    return value


def multiplicative_subgroup(modulus: int, generators: list[int]) -> set[int]:
    """Return the subgroup of units generated by the supplied residues."""
    if modulus <= 1:
        raise ValueError("subgroup modulus must be greater than one")
    subgroup = {1 % modulus}
    frontier = [1 % modulus]
    inverses = []
    for generator in generators:
        if math.gcd(generator, modulus) != 1:
            raise AssertionError("K support is not a unit at the reduced modulus")
        inverses.append(pow(generator, -1, modulus))
    while frontier:
        residue = frontier.pop()
        for generator, inverse in zip(generators, inverses):
            for next_residue in (
                residue * generator % modulus,
                residue * inverse % modulus,
            ):
                if next_residue not in subgroup:
                    subgroup.add(next_residue)
                    frontier.append(next_residue)
    return subgroup


def order_two_to_minus_one(modulus: int) -> int | None:
    """Return the least j>0 with 2^j=-1 mod modulus, if it exists."""
    if math.gcd(2, modulus) != 1:
        return None
    residue = 1 % modulus
    for exponent in range(1, 2 * modulus + 1):
        residue = 2 * residue % modulus
        if residue == modulus - 1:
            return exponent
    return None


def lower_modulus_fiber_profile(
    modulus: int, factorization: list[tuple[int, int]]
) -> dict[str, object]:
    """Classify -1 in the K-supported exponent box at a smaller modulus."""
    if modulus <= 1:
        raise ValueError("lower-modulus fiber requires a nontrivial modulus")
    subgroup = multiplicative_subgroup(modulus, [q for q, _nu in factorization])
    target = modulus - 1
    v2_k = next((nu for q, nu in factorization if q == 2), 0)
    dyadic_budget = v2_k + 1
    order_two_target = order_two_to_minus_one(modulus)

    # Keep exact multiplicities and one canonical shortest exponent vector for each residue.
    profiles: dict[int, tuple[int, int, tuple[int, ...]]] = {
        1 % modulus: (1, 0, ())
    }
    for q, nu in factorization:
        inverse = pow(q, -1, modulus)
        next_profiles: dict[int, tuple[int, int, tuple[int, ...]]] = {}
        for residue, (count, _best_l1, best_vector) in profiles.items():
            for exponent in range(-nu, nu + 1):
                power = pow(q, exponent, modulus) if exponent >= 0 else pow(inverse, -exponent, modulus)
                next_residue = residue * power % modulus
                previous = next_profiles.get(next_residue)
                candidate_l1 = sum(abs(value) for value in best_vector) + abs(exponent)
                candidate_max = max((abs(value) for value in best_vector), default=0)
                candidate_vector = best_vector + (exponent,)
                if previous is None:
                    next_profiles[next_residue] = (
                        count,
                        candidate_l1,
                        candidate_vector,
                    )
                else:
                    previous_count, previous_l1, previous_vector = previous
                    if (candidate_l1, candidate_max, candidate_vector) < (
                        previous_l1,
                        max((abs(value) for value in previous_vector), default=0),
                        previous_vector,
                    ):
                        chosen_l1, chosen_vector = candidate_l1, candidate_vector
                    else:
                        chosen_l1, chosen_vector = previous_l1, previous_vector
                    next_profiles[next_residue] = (
                        previous_count + count,
                        chosen_l1,
                        chosen_vector,
                    )
        profiles = next_profiles

    target_profile = profiles.get(target)
    target_count = 0 if target_profile is None else target_profile[0]
    target_in_subgroup = target in subgroup
    if not target_in_subgroup:
        classification = "G"
    elif target_profile is None:
        classification = "F_box_miss"
    else:
        classification = "F_box_hit"
    return {
        "lower_modulus_subgroup_order": len(subgroup),
        "lower_modulus_target_in_subgroup": target_in_subgroup,
        "lower_modulus_target_count": target_count,
        "lower_modulus_target_min_l1": (
            None if target_profile is None else sum(abs(value) for value in target_profile[2])
        ),
        "lower_modulus_target_min_max": (
            None
            if target_profile is None
            else max((abs(value) for value in target_profile[2]), default=0)
        ),
        "lower_modulus_target_witness": (
            None if target_profile is None else list(target_profile[2])
        ),
        "lower_modulus_classification": classification,
        "lower_modulus_order_two_to_minus_one": order_two_target,
        "lower_modulus_dyadic_budget": dyadic_budget,
        "lower_modulus_dyadic_budget_gap": (
            None
            if order_two_target is None
            else max(order_two_target - dyadic_budget, 0)
        ),
        "lower_modulus_dyadic_budget_admissible": (
            order_two_target is not None and order_two_target <= dyadic_budget
        ),
    }


def audit_orientation(
    row: dict[str, object], source_row: dict[str, object], orientation: str
) -> dict[str, object]:
    if orientation not in {"forward", "reverse"}:
        raise ValueError("unknown orientation")
    prime = int(row["prime"])
    original_R = int(row["R"])
    K = int(row["K"])
    if orientation == "forward":
        A = int(row["formal_A"])
        B = int(row["formal_B"])
    else:
        A = int(row["formal_B"])
        B = int(row["formal_A"])
    factorization = [(int(q), int(nu)) for q, nu in source_row["factorization"]]
    witness = tuple(int(value) for value in source_row["witness_exponents"])
    if orientation == "reverse":
        witness = tuple(-value for value in witness)

    repair_gcd = math.gcd(original_R, B - 1)
    target_divisor = K * A
    candidates: list[dict[str, object]] = []
    for gap in divisors(repair_gcd):
        if gap < 3 or gap > prime - 2 or gap % 4 != 3:
            continue
        if (4 * target_divisor + 1) % gap:
            raise AssertionError("R-factor repair lost the target congruence")
        first_numerator = prime + gap
        if first_numerator % 4:
            raise AssertionError("candidate gap is not integral")
        first_denominator = first_numerator // 4
        repaired_R = (4 * target_divisor + 1) // gap
        repaired_K = first_denominator * repaired_R - target_divisor
        if repaired_K <= 0 or 4 * repaired_K != prime * repaired_R + 1:
            raise AssertionError("candidate did not reconstruct a valid K state")
        if repaired_R % 4 != 3 or math.gcd(repaired_K, repaired_R) != 1:
            raise AssertionError("candidate did not reconstruct an admissible modulus state")
        square_hit = first_denominator * first_denominator % target_divisor == 0
        identity_numerator = 4 * K + gap * gap * (original_R // gap) - 1
        square_deficits: dict[str, int] = {}
        for (q, nu), exponent in zip(factorization, witness):
            first_valuation = valuation(first_denominator, q)
            identity_valuation = valuation(identity_numerator, q) - (2 if q == 2 else 0)
            if identity_valuation != first_valuation:
                raise AssertionError("R-factor q-adic identity did not recover x_m")
            target_exponent = nu + max(exponent, 0)
            deficit = max(target_exponent - 2 * first_valuation, 0)
            if deficit:
                square_deficits[str(q)] = deficit
        if square_hit != (not square_deficits):
            raise AssertionError("square-divisibility and q-adic deficit disagree")
        repair_divisor = math.gcd(target_divisor, first_denominator * first_denominator)
        second_repair_modulus = math.gcd(gap, 4 * repair_divisor + 1)
        second_repair_gaps = admissible_gaps(second_repair_modulus, prime)
        second_repair_square_hits: list[int] = []
        for second_gap in second_repair_gaps:
            second_x = (prime + second_gap) // 4
            if second_x * second_x % repair_divisor == 0:
                second_repair_square_hits.append(second_gap)
        balanced_t = original_R // gap
        if (A + 1) % gap or (B - 1) % gap:
            raise AssertionError("R-factor candidate did not balance both endpoints")
        balanced_u = (A + 1) // gap
        balanced_v = (B - 1) // gap
        balanced_v_coprime_to_t = math.gcd(balanced_v, balanced_t) == 1
        strict_balanced_reduction = balanced_t > 1 and balanced_v_coprime_to_t
        balanced_pair_gcd = math.gcd(balanced_u, balanced_v)
        balanced_u_support_residual = strip_support(balanced_u, [q for q, _nu in factorization])
        balanced_v_support_residual = strip_support(balanced_v, [q for q, _nu in factorization])
        if strict_balanced_reduction:
            reduced_u = balanced_u // balanced_pair_gcd
            reduced_v = balanced_v // balanced_pair_gcd
            if (reduced_u + reduced_v) % balanced_t:
                raise AssertionError("balanced reduction lost the smaller-modulus relation")
            if (reduced_u * pow(reduced_v, -1, balanced_t) + 1) % balanced_t:
                raise AssertionError("balanced reduction lost the target residue")
            lower_modulus_profile = lower_modulus_fiber_profile(balanced_t, factorization)
        else:
            lower_modulus_profile = {
                "lower_modulus_subgroup_order": None,
                "lower_modulus_target_in_subgroup": None,
                "lower_modulus_target_count": None,
                "lower_modulus_target_min_l1": None,
                "lower_modulus_target_min_max": None,
                "lower_modulus_target_witness": None,
                "lower_modulus_classification": "not_applicable",
                "lower_modulus_order_two_to_minus_one": None,
                "lower_modulus_dyadic_budget": None,
                "lower_modulus_dyadic_budget_gap": None,
                "lower_modulus_dyadic_budget_admissible": None,
            }
        candidates.append(
            {
                "gap": gap,
                "target_divisor": target_divisor,
                "first_denominator": first_denominator,
                "target_divisor_divides_first_square": square_hit,
                "square_deficits": square_deficits,
                "square_deficit_layers": sum(square_deficits.values()),
                "deficient_q_coordinate_count": len(square_deficits),
                "repair_divisor": repair_divisor,
                "second_repair_modulus": second_repair_modulus,
                "second_repair_gaps": second_repair_gaps,
                "second_repair_square_hits": second_repair_square_hits,
                "balanced_t": balanced_t,
                "balanced_pair_gcd": balanced_pair_gcd,
                "balanced_v_coprime_to_t": balanced_v_coprime_to_t,
                "strict_balanced_reduction": strict_balanced_reduction,
                "balanced_u_support_residual": balanced_u_support_residual,
                "balanced_v_support_residual": balanced_v_support_residual,
                "balanced_support_preserved": (
                    strict_balanced_reduction
                    and balanced_u_support_residual == 1
                    and balanced_v_support_residual == 1
                ),
                **lower_modulus_profile,
                "repaired_R": repaired_R,
                "repaired_K": repaired_K,
            }
        )

    return {
        "orientation": orientation,
        "original_R": original_R,
        "formal_A": A,
        "formal_B": B,
        "repair_gcd": repair_gcd,
        "repair_gcd_is_nontrivial": repair_gcd > 1,
        "candidate_count": len(candidates),
        "square_hit_count": sum(
            int(candidate["target_divisor_divides_first_square"]) for candidate in candidates
        ),
        "square_deficit_layers": sum(
            int(candidate["square_deficit_layers"]) for candidate in candidates
        ),
        "deficient_q_coordinate_count": sum(
            int(candidate["deficient_q_coordinate_count"]) for candidate in candidates
        ),
        "second_repair_modulus_nontrivial_count": sum(
            int(candidate["second_repair_modulus"] > 1) for candidate in candidates
        ),
        "second_repair_gap_candidate_count": sum(
            len(candidate["second_repair_gaps"]) for candidate in candidates
        ),
        "second_repair_square_hit_count": sum(
            len(candidate["second_repair_square_hits"]) for candidate in candidates
        ),
        "strict_balanced_reduction_count": sum(
            int(candidate["strict_balanced_reduction"]) for candidate in candidates
        ),
        "balanced_support_preserved_count": sum(
            int(candidate["balanced_support_preserved"]) for candidate in candidates
        ),
        "balanced_external_support_count": sum(
            int(
                candidate["strict_balanced_reduction"]
                and candidate["balanced_u_support_residual"] > 1
                and candidate["balanced_v_support_residual"] > 1
            )
            for candidate in candidates
        ),
        "lower_modulus_f_box_hit_count": sum(
            int(candidate["lower_modulus_classification"] == "F_box_hit")
            for candidate in candidates
        ),
        "lower_modulus_f_box_miss_count": sum(
            int(candidate["lower_modulus_classification"] == "F_box_miss")
            for candidate in candidates
        ),
        "lower_modulus_g_count": sum(
            int(candidate["lower_modulus_classification"] == "G") for candidate in candidates
        ),
        "lower_modulus_order_two_target_count": sum(
            int(candidate["lower_modulus_order_two_to_minus_one"] is not None)
            for candidate in candidates
        ),
        "lower_modulus_dyadic_budget_admissible_count": sum(
            int(candidate["lower_modulus_dyadic_budget_admissible"] is True)
            for candidate in candidates
        ),
        "candidates": candidates,
    }


