"""Compute exact coordinate and optimistic-box boundaries for frozen F states.

For a target fiber

    F = {z in Z^r : product(q_i**z_i) == -1 (mod R)}

and box bounds nu_i, the coordinate floor at q_j is

    delta_j = min_{z in F} max(0, abs(z_j) - nu_j).

Quotienting the support group by the subgroup generated by all q_i except
q_j makes this a one-dimensional calculation.  The script applies that exact
calculation to every support coordinate of all 253 frozen square-terminal F
states, and separately checks whether the complete target fiber meets the box
obtained by adding the two source-block height maxima.  It does not claim that
either finite model is an overflow-to-carrier injection.
"""

