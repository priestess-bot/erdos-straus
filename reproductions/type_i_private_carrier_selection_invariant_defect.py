def file_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_guarded(path: Path) -> dict[str, object]:
    actual = file_sha256(path)
    if actual != EXPECTED_INPUT_SHA256[path.name]:
        raise AssertionError(f"authoritative input hash changed: {path.name}")
    return json.loads(path.read_text(encoding="utf-8"))


def exact_factorization(value: int) -> list[tuple[int, int]]:
    factors = sorted(
        (int(prime), int(exponent))
        for prime, exponent in sympy.factorint(value).items()
    )
    if math.prod(prime**exponent for prime, exponent in factors) != value:
        raise AssertionError("factorization failed to reconstruct")
    if any(not sympy.isprime(prime) for prime, _ in factors):
        raise AssertionError("factorization contains a nonprime base")
    return factors


def component_lattice_hnf(
    generator_logs: list[list[int]], component_orders: list[int]
) -> Matrix:
    dimension = len(component_orders)
    if dimension == 0:
        raise AssertionError("the unit group has no cyclic components")
    if any(len(vector) != dimension for vector in generator_logs):
        raise AssertionError("generator log vector has the wrong dimension")
    columns = [*generator_logs]
    columns.extend(
        [
            [component_orders[row] if row == column else 0 for row in range(dimension)]
            for column in range(dimension)
        ]
    )
    lattice = Matrix(
        dimension,
        len(columns),
        lambda row, column: columns[column][row],
    )
    hnf = hermite_normal_form(lattice)
    if hnf.shape != (dimension, dimension):
        raise AssertionError("HNF does not have full rank")
    return hnf


def lattice_solution(hnf: Matrix, target: list[int]) -> list[int] | None:
    dimension = len(target)
    if hnf.shape != (dimension, dimension):
        raise AssertionError("HNF membership dimension mismatch")
    if any(
        int(hnf[row, column])
        for row in range(dimension)
        for column in range(row)
    ):
        raise AssertionError("HNF is not upper triangular")
    coordinates = [0] * dimension
    for row in range(dimension - 1, -1, -1):
        diagonal = int(hnf[row, row])
        numerator = target[row] - sum(
            int(hnf[row, column]) * coordinates[column]
            for column in range(row + 1, dimension)
        )
        if diagonal <= 0 or numerator % diagonal:
            return None
        coordinates[row] = numerator // diagonal
    return coordinates


def lattice_contains(hnf: Matrix, target: list[int]) -> bool:
    return lattice_solution(hnf, target) is not None


def lattice_index(hnf: Matrix) -> int:
    return math.prod(int(hnf[index, index]) for index in range(hnf.rows))


def unit_group_logs(
    modulus: int, support_primes: list[int]
) -> tuple[list[dict[str, int]], list[list[int]], list[int]]:
    components = []
    for prime, exponent in exact_factorization(modulus):
        component_modulus = prime**exponent
        order = int(sympy.totient(component_modulus))
        root = int(sympy.primitive_root(component_modulus))
        components.append(
            {"modulus": component_modulus, "order": order, "primitive_root": root}
        )
    target = [component["order"] // 2 for component in components]
    logs = []
    for support_prime in support_primes:
        vector = [
            int(
                sympy.discrete_log(
                    component["modulus"],
                    support_prime % component["modulus"],
                    component["primitive_root"],
                )
            )
            for component in components
        ]
        for component, logarithm in zip(components, vector):
            if (
                pow(
                    component["primitive_root"],
                    logarithm,
                    component["modulus"],
                )
                != support_prime % component["modulus"]
            ):
                raise AssertionError("discrete logarithm did not reconstruct")
        logs.append(vector)
    if any(
        pow(component["primitive_root"], value, component["modulus"])
        != component["modulus"] - 1
        for component, value in zip(components, target)
    ):
        raise AssertionError("target logs do not reconstruct -1")
    return components, logs, target


def coordinate_floors(
    modulus: int, factors: list[tuple[int, int]]
) -> dict[str, object]:
    support_primes = [prime for prime, _ in factors]
    components, generator_logs, target = unit_group_logs(modulus, support_primes)
    component_orders = [component["order"] for component in components]
    full_hnf = component_lattice_hnf(generator_logs, component_orders)
    if not lattice_contains(full_hnf, target):
        raise AssertionError("an F state target left its full support subgroup")
    full_index = lattice_index(full_hnf)
    coordinate_records = []
    for selected_index, (selected_prime, bound) in enumerate(factors):
        selected_log = generator_logs[selected_index]
        other_logs = [
            vector
            for index, vector in enumerate(generator_logs)
            if index != selected_index
        ]
        other_hnf = component_lattice_hnf(other_logs, component_orders)
        other_index = lattice_index(other_hnf)
        quotient_order, remainder = divmod(other_index, full_index)
        if remainder or quotient_order < 1:
            raise AssertionError("invalid support quotient order")
        order_target = [quotient_order * value for value in selected_log]
        order_coordinates = lattice_solution(other_hnf, order_target)
        if order_coordinates is None:
            raise AssertionError(
                "selected generator does not have the certified quotient order"
            )

        target_class = None
        target_coordinates = None
        for exponent in range(quotient_order):
            difference = [
                target_value - exponent * selected_value
                for target_value, selected_value in zip(target, selected_log)
            ]
            coordinates = lattice_solution(other_hnf, difference)
            if coordinates is not None:
                target_class = exponent
                target_coordinates = coordinates
                break
        if target_class is None or target_coordinates is None:
            raise AssertionError("target has no exponent class in the cyclic quotient")
        if quotient_order > 1 and lattice_contains(
            other_hnf,
            [
                target_value - (target_class + 1) * selected_value
                for target_value, selected_value in zip(target, selected_log)
            ],
        ):
            raise AssertionError(
                "target exponent class is not unique modulo the quotient order"
            )

        signed_candidates = {target_class, target_class - quotient_order}
        minimum_signed_exponent = min(
            signed_candidates, key=lambda value: (abs(value), value)
        )
        minimum_absolute_exponent = abs(minimum_signed_exponent)
        overflow_floor = max(0, minimum_absolute_exponent - bound)
        minimum_difference = [
            target_value - minimum_signed_exponent * selected_value
            for target_value, selected_value in zip(target, selected_log)
        ]
        minimum_coordinates = lattice_solution(other_hnf, minimum_difference)
        if minimum_coordinates is None:
            raise AssertionError("minimum coordinate-floor relation failed")
        coordinate_records.append(
            {
                "support_index": selected_index,
                "support_prime": selected_prime,
                "box_exponent_bound": bound,
                "other_support_ambient_index": other_index,
                "selected_coordinate_quotient_order": quotient_order,
                "target_exponent_class": target_class,
                "minimum_signed_exponent": minimum_signed_exponent,
                "minimum_absolute_exponent": minimum_absolute_exponent,
                "selection_invariant_overflow_floor": overflow_floor,
            }
        )
    return {
        "full_support_ambient_index": full_index,
        "coordinate_floors": coordinate_records,
    }


def histogram(values: list[int]) -> dict[str, int]:
    return {str(key): count for key, count in sorted(Counter(values).items())}


def valuation(value: int, prime: int) -> int:
    exponent = 0
    while value % prime == 0:
        value //= prime
        exponent += 1
    return exponent


