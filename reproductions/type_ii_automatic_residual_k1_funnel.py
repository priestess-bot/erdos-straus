def prime_factorization_from_spf(value: int, spf: list[int]) -> dict[int, int]:
    """Return the prime factorization of a positive table-covered integer."""
    if value <= 0 or value >= len(spf):
        raise ValueError("SPF table does not cover the requested value")
    factors: dict[int, int] = {}
    while value > 1:
        prime = spf[value]
        exponent = 0
        while value % prime == 0:
            value //= prime
            exponent += 1
        factors[prime] = exponent
    return factors


def distinct_prime_factors_from_spf(value: int, spf: list[int]) -> list[int]:
    """Return the distinct prime factors of a positive table-covered integer."""
    return list(prime_factorization_from_spf(value, spf))


def unit_prime_factor_multiset_from_spf(
    value: int, modulus: int, spf: list[int]
) -> list[int]:
    """Return prime factors of value coprime to modulus, with multiplicity."""
    if modulus < 2:
        raise ValueError("modulus must be at least two")
    factors = prime_factorization_from_spf(value, spf)
    return [
        prime
        for prime, exponent in factors.items()
        if modulus % prime
        for _ in range(exponent)
    ]


def euler_phi_from_spf(value: int, spf: list[int]) -> int:
    """Compute Euler's totient of a positive table-covered integer."""
    if value < 1:
        raise ValueError("value must be positive")
    result = value
    for prime in prime_factorization_from_spf(value, spf):
        result -= result // prime
    return result


def prefix_product_one_divisor(
    factors: list[int], modulus: int
) -> int | None:
    """Construct a nonempty subproduct congruent to one by prefix collision."""
    prefix = 1
    first_prefix_index = {1: 0}
    exact_prefix_products = [1]
    for index, factor in enumerate(factors, start=1):
        prefix = prefix * factor % modulus
        exact_prefix_products.append(exact_prefix_products[-1] * factor)
        previous_index = first_prefix_index.get(prefix)
        if previous_index is not None:
            divisor = exact_prefix_products[index] // exact_prefix_products[
                previous_index
            ]
            if divisor <= 1 or divisor % modulus != 1:
                raise AssertionError("prefix collision did not produce a unit divisor")
            return divisor
        first_prefix_index[prefix] = index
    return None


def generated_unit_residue_subgroup(
    factors: list[int], modulus: int
) -> frozenset[int]:
    """Return the subgroup of units generated by the supplied factor residues."""
    subgroup = {1}
    for factor in sorted(set(factor % modulus for factor in factors)):
        if math.gcd(factor, modulus) != 1:
            raise ValueError("a subgroup generator must be a unit")
        powers = []
        power = 1
        while True:
            powers.append(power)
            power = power * factor % modulus
            if power == 1:
                break
        subgroup = {
            element * power % modulus
            for element in subgroup
            for power in powers
        }
    return frozenset(subgroup)


def p_group_davenport_data(
    subgroup: frozenset[int], modulus: int
) -> tuple[int, tuple[int, ...], int] | None:
    """Return the exact Davenport data when ``subgroup`` is an abelian p-group.

    For H = direct_sum C_(p**a_i), the p-group formula is
    D(H)=1+sum_i(p**a_i-1).  The exponents are recovered from the exact
    cardinalities of H[p**k], so no invariant-factor guess is used.
    """
    order = len(subgroup)
    if order == 1:
        return 1, (), 1
    remaining = order
    prime = None
    candidate = 2
    while candidate * candidate <= remaining:
        if remaining % candidate == 0:
            if prime is not None:
                return None
            prime = candidate
            while remaining % candidate == 0:
                remaining //= candidate
        candidate += 1
    if remaining > 1:
        if prime is not None:
            return None
        prime = remaining
    if prime is None:
        return None

    exponents_at_least: list[int] = []
    previous_log = 0
    prime_power = prime
    while True:
        torsion_count = sum(
            pow(element, prime_power, modulus) == 1 for element in subgroup
        )
        if torsion_count < 1 or torsion_count > order:
            raise AssertionError("invalid p-primary torsion count")
        log_count = 0
        count = torsion_count
        while count > 1:
            if count % prime:
                raise AssertionError("torsion count is not a p-power")
            count //= prime
            log_count += 1
        components_at_least = log_count - previous_log
        exponents_at_least.append(components_at_least)
        previous_log = log_count
        if torsion_count == order:
            break
        prime_power *= prime
        if prime_power > order * prime:
            raise AssertionError("p-primary torsion did not exhaust subgroup")

    exponents: list[int] = []
    for index, count_at_least in enumerate(exponents_at_least):
        next_count = (
            exponents_at_least[index + 1]
            if index + 1 < len(exponents_at_least)
            else 0
        )
        exponents.extend([index + 1] * (count_at_least - next_count))
    if prime ** sum(exponents) != order:
        raise AssertionError("recovered p-group exponents have wrong order")
    davenport = 1 + sum(prime**exponent - 1 for exponent in exponents)
    return prime, tuple(exponents), davenport


def integer_prime_factorization(value: int) -> dict[int, int]:
    """Factor a small positive integer without relying on the SPF table."""
    if value < 1:
        raise ValueError("value must be positive")
    factors: dict[int, int] = {}
    divisor = 2
    while divisor * divisor <= value:
        while value % divisor == 0:
            factors[divisor] = factors.get(divisor, 0) + 1
            value //= divisor
        divisor += 1
    if value > 1:
        factors[value] = factors.get(value, 0) + 1
    return factors


def primary_component_exponents(
    subgroup: frozenset[int],
    modulus: int,
    prime: int,
    primary_order: int,
) -> tuple[int, ...]:
    """Recover elementary-divisor exponents of one primary component."""
    if primary_order < 1:
        raise ValueError("primary order must be positive")
    exponents_at_least: list[int] = []
    previous_log = 0
    prime_power = prime
    while True:
        torsion_count = sum(
            pow(element, prime_power, modulus) == 1 for element in subgroup
        )
        if torsion_count < 1 or torsion_count > primary_order:
            raise AssertionError("invalid primary torsion count")
        log_count = 0
        count = torsion_count
        while count > 1:
            if count % prime:
                raise AssertionError("primary torsion count is not a prime power")
            count //= prime
            log_count += 1
        components_at_least = log_count - previous_log
        if components_at_least < 0:
            raise AssertionError("primary torsion dimensions decreased")
        exponents_at_least.append(components_at_least)
        previous_log = log_count
        if torsion_count == primary_order:
            break
        prime_power *= prime
        if prime_power > primary_order * prime:
            raise AssertionError("primary torsion did not exhaust subgroup")

    exponents: list[int] = []
    for index, count_at_least in enumerate(exponents_at_least):
        next_count = (
            exponents_at_least[index + 1]
            if index + 1 < len(exponents_at_least)
            else 0
        )
        if count_at_least < next_count:
            raise AssertionError("primary component counts are not nested")
        exponents.extend([index + 1] * (count_at_least - next_count))
    if prime ** sum(exponents) != primary_order:
        raise AssertionError("recovered primary exponents have wrong order")
    return tuple(exponents)


def abelian_invariant_factor_data(
    subgroup: frozenset[int], modulus: int
) -> tuple[tuple[int, ...], tuple[tuple[int, tuple[int, ...]], ...]]:
    """Recover invariant factors and primary exponents of a finite unit subgroup."""
    order = len(subgroup)
    if order == 1:
        return (1,), ()
    factorization = integer_prime_factorization(order)
    primary_data = tuple(
        (
            prime,
            primary_component_exponents(
                subgroup, modulus, prime, prime**exponent
            ),
        )
        for prime, exponent in sorted(factorization.items())
    )
    rank = max(len(exponents) for _, exponents in primary_data)
    invariant_factors = [1] * rank
    for prime, exponents in primary_data:
        padded = [0] * (rank - len(exponents)) + list(exponents)
        for index, exponent in enumerate(padded):
            invariant_factors[index] *= prime**exponent
    if any(
        invariant_factors[index + 1] % invariant_factors[index]
        for index in range(rank - 1)
    ):
        raise AssertionError("invariant factors are not nested")
    if math.prod(invariant_factors) != order:
        raise AssertionError("invariant factors have wrong order")
    return tuple(invariant_factors), primary_data


def rank_two_davenport_data(
    subgroup: frozenset[int], modulus: int
) -> tuple[tuple[int, ...], tuple[tuple[int, tuple[int, ...]], ...], int] | None:
    """Return exact Davenport data for cyclic or rank-two abelian subgroups."""
    invariant_factors, primary_data = abelian_invariant_factor_data(
        subgroup, modulus
    )
    if len(invariant_factors) > 2:
        return None
    davenport = 1 + sum(invariant - 1 for invariant in invariant_factors)
    return invariant_factors, primary_data, davenport


def nonempty_subproduct_one(factors: list[int], modulus: int) -> int | None:
    """Construct any nonempty subproduct equal to one modulo ``modulus``."""
    reachable: dict[int, tuple[int, int]] = {1: (1, 0)}
    for factor in factors:
        previous = tuple(reachable.items())
        for residue, (product, length) in previous:
            next_residue = residue * factor % modulus
            next_product = product * factor
            if next_residue == 1:
                if next_product <= 1 or next_product % modulus != 1:
                    raise AssertionError("subproduct witness is not nontrivial")
                return next_product
            if next_residue not in reachable:
                reachable[next_residue] = (next_product, length + 1)
    return None


def single_prime_shared_profile(
    records: list[dict[str, object]], gap_cap: int, spf: list[int]
) -> dict[str, object]:
    """Test whether a non-k=1 point has any one-prime shared certificate.

    A hit requires one legal gap with both a Type II certificate and a prime
    divisor q of p+m satisfying q == 1 modulo m. This is stronger than
    inspecting the least-gap shared witness returned by the main funnel.
    """
    by_least_gap: Counter[int] = Counter()
    hits: list[dict[str, int]] = []
    misses: list[int] = []
    for record in records:
        prime = int(record["prime"])
        candidates: list[tuple[int, int]] = []
        for gap in range(3, min(gap_cap, prime - 2) + 1, 4):
            certificate = short_certificate.type_ii_residue_certificate(
                prime, gap, spf
            )
            if certificate is None:
                continue
            for shared_prime in distinct_prime_factors_from_spf(prime + gap, spf):
                if shared_prime % gap != 1:
                    continue
                first_scale = (shared_prime - 1) // gap
                witness = short_certificate.type_ii_scaled_first_tail_deflation_witness(
                    prime, gap, first_scale, spf
                )
                if witness is None:
                    raise AssertionError("single-prime shared candidate did not lift")
                candidates.append((gap, shared_prime))
        if not candidates:
            misses.append(prime)
            continue
        gap, shared_prime = min(candidates)
        by_least_gap[gap] += 1
        hits.append(
            {
                "prime": prime,
                "gap": gap,
                "shared_prime": shared_prime,
                "first_scale": (shared_prime - 1) // gap,
            }
        )
    return {
        "arithmetic": (
            "complete legal-gap Type II certificate scan plus exact prime-factor "
            "checks of p+m and scaled-first certificate reconstruction"
        ),
        "scope_note": (
            "A miss rules out only one-prime shared divisors through the stated "
            "gap cap; a composite shared divisor may still work."
        ),
        "single_prime_shared_count": len(hits),
        "single_prime_shared_by_least_gap": dict(sorted(by_least_gap.items())),
        "single_prime_shared_hits": hits,
        "single_prime_shared_misses": misses,
    }


def subgroup_threshold_shared_profile(
    records: list[dict[str, object]], gap_cap: int, spf: list[int]
) -> dict[str, object]:
    """Apply the generated-subgroup prefix-product threshold at every gap."""
    witnesses: list[dict[str, int]] = []
    misses: list[int] = []
    for record in records:
        prime = int(record["prime"])
        candidates: list[tuple[int, int, int, int]] = []
        for gap in range(3, min(gap_cap, prime - 2) + 1, 4):
            certificate = short_certificate.type_ii_residue_certificate(
                prime, gap, spf
            )
            if certificate is None:
                continue
            factors = unit_prime_factor_multiset_from_spf(prime + gap, gap, spf)
            subgroup_order = len(generated_unit_residue_subgroup(factors, gap))
            if len(factors) < subgroup_order:
                continue
            shared_divisor = prefix_product_one_divisor(factors, gap)
            if shared_divisor is None:
                raise AssertionError("subgroup threshold did not force a divisor")
            first_scale = (shared_divisor - 1) // gap
            witness = short_certificate.type_ii_scaled_first_tail_deflation_witness(
                prime, gap, first_scale, spf
            )
            if witness is None:
                raise AssertionError("subgroup-threshold candidate did not lift")
            candidates.append((gap, shared_divisor, len(factors), subgroup_order))
        if not candidates:
            misses.append(prime)
            continue
        gap, shared_divisor, factor_count, subgroup_order = min(candidates)
        witnesses.append(
            {
                "prime": prime,
                "gap": gap,
                "shared_divisor": shared_divisor,
                "first_scale": (shared_divisor - 1) // gap,
                "unit_factor_multiplicity": factor_count,
                "generated_subgroup_order": subgroup_order,
            }
        )
    return {
        "arithmetic": (
            "complete legal-gap Type II certificate scan; factor residues "
            "generate a finite subgroup H, and at least |H| factors force a "
            "prefix-product collision within H"
        ),
        "scope_note": (
            "This is a sufficient condition only. A miss may still have a "
            "shared divisor through a shorter zero-product subsequence."
        ),
        "subgroup_threshold_shared_count": len(witnesses),
        "subgroup_threshold_shared_witnesses": witnesses,
        "subgroup_threshold_shared_misses": misses,
    }


def p_group_davenport_shared_profile(
    records: list[dict[str, object]], gap_cap: int, spf: list[int]
) -> dict[str, object]:
    """Apply the exact Davenport threshold for p-primary residue subgroups."""
    witnesses: list[dict[str, object]] = []
    misses: list[int] = []
    p_group_gap_count = 0
    threshold_eligible_gap_count = 0
    threshold_histogram: Counter[int] = Counter()
    group_prime_histogram: Counter[int] = Counter()
    for record in records:
        prime = int(record["prime"])
        candidates: list[tuple[int, int, int, int, int, int, tuple[int, ...]]] = []
        for gap in range(3, min(gap_cap, prime - 2) + 1, 4):
            certificate = short_certificate.type_ii_residue_certificate(
                prime, gap, spf
            )
            if certificate is None:
                continue
            factors = unit_prime_factor_multiset_from_spf(prime + gap, gap, spf)
            subgroup = generated_unit_residue_subgroup(factors, gap)
            davenport_data = p_group_davenport_data(subgroup, gap)
            if davenport_data is None:
                continue
            p_group_gap_count += 1
            group_prime, exponents, davenport = davenport_data
            threshold_histogram[davenport] += 1
            group_prime_histogram[group_prime] += 1
            if len(factors) < davenport:
                continue
            threshold_eligible_gap_count += 1
            shared_divisor = nonempty_subproduct_one(factors, gap)
            if shared_divisor is None:
                raise AssertionError("p-group Davenport threshold did not force a divisor")
            first_scale = (shared_divisor - 1) // gap
            witness = short_certificate.type_ii_scaled_first_tail_deflation_witness(
                prime, gap, first_scale, spf
            )
            if witness is None:
                raise AssertionError("p-group Davenport candidate did not lift")
            candidates.append(
                (
                    gap,
                    shared_divisor,
                    len(factors),
                    len(subgroup),
                    davenport,
                    group_prime,
                    exponents,
                )
            )
        if not candidates:
            misses.append(prime)
            continue
        (
            gap,
            shared_divisor,
            factor_count,
            subgroup_order,
            davenport,
            group_prime,
            exponents,
        ) = min(candidates)
        witnesses.append(
            {
                "prime": prime,
                "gap": gap,
                "shared_divisor": shared_divisor,
                "first_scale": (shared_divisor - 1) // gap,
                "unit_factor_multiplicity": factor_count,
                "generated_subgroup_order": subgroup_order,
                "p_group_prime": group_prime,
                "davenport_constant": davenport,
                "p_group_exponents": list(exponents),
            }
        )
    return {
        "arithmetic": (
            "complete legal-gap Type II certificate scan; for p-primary generated "
            "unit subgroups, exact H[p^k] counts recover the p-group Davenport constant "
            "and a dynamic subproduct witness"
        ),
        "scope_note": (
            "This is a sufficient condition only. It applies only when the generated "
            "residue subgroup is a finite abelian p-group; all other gaps remain outside "
            "this threshold."
        ),
        "p_group_davenport_shared_count": len(witnesses),
        "p_group_davenport_shared_witnesses": witnesses,
        "p_group_davenport_shared_misses": misses,
        "p_group_gap_count": p_group_gap_count,
        "threshold_eligible_gap_count": threshold_eligible_gap_count,
        "davenport_threshold_histogram": dict(sorted(threshold_histogram.items())),
        "p_group_prime_histogram": dict(sorted(group_prime_histogram.items())),
    }


