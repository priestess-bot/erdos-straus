def prime_power_shared_profile(
    records: list[dict[str, object]], gap_cap: int, spf: list[int]
) -> dict[str, object]:
    """Profile shared certificates whose divisor is one prime power.

    The profile considers every q^e dividing p+m, including e=1.
    It separately records points rescued by a proper prime power after all
    one-prime candidates have failed.
    """
    by_least_gap: Counter[int] = Counter()
    hits: list[dict[str, int]] = []
    proper_power_hits: list[dict[str, int]] = []
    proper_power_rescues: list[dict[str, int]] = []
    misses: list[int] = []
    for record in records:
        prime = int(record["prime"])
        candidates: list[tuple[int, int, int, int]] = []
        prime_candidates: list[tuple[int, int, int, int]] = []
        proper_power_candidates: list[tuple[int, int, int, int]] = []
        for gap in range(3, min(gap_cap, prime - 2) + 1, 4):
            certificate = short_certificate.type_ii_residue_certificate(
                prime, gap, spf
            )
            if certificate is None:
                continue
            for base, exponent in prime_factorization_from_spf(prime + gap, spf).items():
                power = 1
                for power_exponent in range(1, exponent + 1):
                    power *= base
                    if power % gap != 1:
                        continue
                    first_scale = (power - 1) // gap
                    witness = short_certificate.type_ii_scaled_first_tail_deflation_witness(
                        prime, gap, first_scale, spf
                    )
                    if witness is None:
                        raise AssertionError(
                            "prime-power shared candidate did not lift"
                        )
                    candidate = (gap, power, base, power_exponent)
                    candidates.append(candidate)
                    if power_exponent == 1:
                        prime_candidates.append(candidate)
                    else:
                        proper_power_candidates.append(candidate)
        if not candidates:
            misses.append(prime)
            continue
        gap, power, base, exponent = min(candidates)
        by_least_gap[gap] += 1
        hits.append(
            {
                "prime": prime,
                "gap": gap,
                "shared_prime_power": power,
                "base_prime": base,
                "exponent": exponent,
                "first_scale": (power - 1) // gap,
            }
        )
        if proper_power_candidates:
            gap, power, base, exponent = min(proper_power_candidates)
            proper_power_hits.append(
                {
                    "prime": prime,
                    "gap": gap,
                    "shared_prime_power": power,
                    "base_prime": base,
                    "exponent": exponent,
                    "first_scale": (power - 1) // gap,
                }
            )
            if not prime_candidates:
                proper_power_rescues.append(proper_power_hits[-1])
    return {
        "arithmetic": (
            "complete legal-gap Type II certificate scan plus exact "
            "prime-power factor checks of p+m and scaled-first certificate "
            "reconstruction"
        ),
        "scope_note": (
            "A miss rules out only one-prime-power shared divisors through "
            "the stated gap cap; a divisor involving multiple distinct "
            "primes may still work."
        ),
        "prime_power_shared_count": len(hits),
        "prime_power_shared_by_least_gap": dict(sorted(by_least_gap.items())),
        "prime_power_shared_hits": hits,
        "proper_prime_power_shared_count": len(proper_power_hits),
        "proper_prime_power_shared_hits": proper_power_hits,
        "proper_prime_power_rescues_after_single_prime_miss": proper_power_rescues,
        "prime_power_shared_misses": misses,
    }


def multi_prime_support_profile(
    records: list[dict[str, object]], gap_cap: int, spf: list[int]
) -> dict[str, object]:
    """Find the smallest distinct-prime support of every shared certificate."""
    support_histogram: Counter[int] = Counter()
    witnesses: list[dict[str, int]] = []
    misses: list[int] = []
    for record in records:
        prime = int(record["prime"])
        candidates: list[tuple[int, int, int]] = []
        for gap in range(3, min(gap_cap, prime - 2) + 1, 4):
            certificate = short_certificate.type_ii_residue_certificate(
                prime, gap, spf
            )
            if certificate is None:
                continue
            for shared_divisor in short_certificate.positive_divisors_from_spf(
                prime + gap, spf
            ):
                if shared_divisor == 1 or (shared_divisor - 1) % gap:
                    continue
                first_scale = (shared_divisor - 1) // gap
                witness = short_certificate.type_ii_scaled_first_tail_deflation_witness(
                    prime, gap, first_scale, spf
                )
                if witness is None:
                    raise AssertionError("shared-divisor candidate did not lift")
                support_size = len(
                    prime_factorization_from_spf(shared_divisor, spf)
                )
                candidates.append((support_size, gap, shared_divisor))
        if not candidates:
            misses.append(prime)
            continue
        support_size, gap, shared_divisor = min(candidates)
        support_histogram[support_size] += 1
        witnesses.append(
            {
                "prime": prime,
                "minimum_distinct_prime_support": support_size,
                "gap": gap,
                "shared_divisor": shared_divisor,
                "first_scale": (shared_divisor - 1) // gap,
            }
        )
    return {
        "arithmetic": (
            "complete legal-gap Type II certificate scan, exhaustive divisor "
            "enumeration of p+m, exact factor support counts, and scaled-first "
            "certificate reconstruction"
        ),
        "scope_note": (
            "The minimum is over shared certificates through the stated gap "
            "cap; it does not assert a uniform all-prime bound."
        ),
        "minimum_distinct_prime_support_histogram": dict(
            sorted(support_histogram.items())
        ),
        "minimum_distinct_prime_support_witnesses": witnesses,
        "minimum_distinct_prime_support_misses": misses,
    }


def minimum_factor_length_profile(
    records: list[dict[str, object]], gap_cap: int, spf: list[int]
) -> dict[str, object]:
    """Find the shortest prime-factor zero product in every shared certificate."""
    length_histogram: Counter[int] = Counter()
    witnesses: list[dict[str, int]] = []
    misses: list[int] = []
    for record in records:
        prime = int(record["prime"])
        candidates: list[tuple[int, int, int]] = []
        for gap in range(3, min(gap_cap, prime - 2) + 1, 4):
            certificate = short_certificate.type_ii_residue_certificate(
                prime, gap, spf
            )
            if certificate is None:
                continue
            for shared_divisor in short_certificate.positive_divisors_from_spf(
                prime + gap, spf
            ):
                if shared_divisor == 1 or (shared_divisor - 1) % gap:
                    continue
                first_scale = (shared_divisor - 1) // gap
                witness = short_certificate.type_ii_scaled_first_tail_deflation_witness(
                    prime, gap, first_scale, spf
                )
                if witness is None:
                    raise AssertionError("shared-divisor candidate did not lift")
                factor_length = sum(
                    prime_factorization_from_spf(shared_divisor, spf).values()
                )
                candidates.append((factor_length, gap, shared_divisor))
        if not candidates:
            misses.append(prime)
            continue
        factor_length, gap, shared_divisor = min(candidates)
        length_histogram[factor_length] += 1
        witnesses.append(
            {
                "prime": prime,
                "minimum_factor_multiplicity": factor_length,
                "gap": gap,
                "shared_divisor": shared_divisor,
                "first_scale": (shared_divisor - 1) // gap,
            }
        )
    return {
        "arithmetic": (
            "complete legal-gap Type II certificate scan, exhaustive divisor "
            "enumeration of p+m, factor multiplicity counts, and scaled-first "
            "certificate reconstruction"
        ),
        "scope_note": (
            "The minimum is over shared certificates through the stated gap "
            "cap; it is not a uniform all-prime zero-product bound."
        ),
        "minimum_factor_multiplicity_histogram": dict(sorted(length_histogram.items())),
        "minimum_factor_multiplicity_witnesses": witnesses,
        "minimum_factor_multiplicity_misses": misses,
    }


def run_audit(
    limit: int,
    gap_cap: int = 239,
    include_single_prime_profile: bool = False,
    include_subgroup_threshold_profile: bool = False,
    include_p_group_davenport_profile: bool = False,
    include_rank_two_davenport_profile: bool = False,
    include_totient_threshold_profile: bool = False,
    include_prime_power_profile: bool = False,
    include_support_profile: bool = False,
    include_factor_length_profile: bool = False,
) -> dict[str, object]:
    """Run the exact four-auto-gap residual funnel through k=1 and k>1."""
    if limit < 73 or gap_cap < 3:
        raise ValueError("limit must be at least 73 and gap_cap at least 3")
    spf = short_certificate.smallest_prime_factors(limit + gap_cap)
    counts = {
        "four_auto_gap_residual": 0,
        "k1_hit": 0,
        "non_k1": 0,
        "non_k1_shared_hit": 0,
    }
    scale_histogram: Counter[int] = Counter()
    non_k1_records = []
    core_prime_count = 0
    for prime in short_certificate.primes_up_to(limit):
        if prime % 24 != 1:
            continue
        core_prime_count += 1
        if gap_23.profile_prime(prime, spf).category != "no_type_ii_3_7_11_23":
            continue
        counts["four_auto_gap_residual"] += 1
        k1_witness = short_certificate.first_type_ii_tail_deflation_witness(
            prime, spf
        )
        if k1_witness is not None:
            counts["k1_hit"] += 1
            continue
        counts["non_k1"] += 1
        witness = short_certificate.type_ii_shared_divisor_tail_deflation_scan(
            prime, gap_cap, spf
        )
        if witness is None:
            non_k1_records.append({"prime": prime, "witness": None})
            continue
        counts["non_k1_shared_hit"] += 1
        scale_histogram[witness.first_scale] += 1
        non_k1_records.append(
            {
                "prime": prime,
                "gap": witness.gap,
                "first_scale": witness.first_scale,
                "shared_divisor": witness.first_scale * witness.gap + 1,
                "certificate_divisor": witness.certificate.divisor,
            }
        )
    if counts["four_auto_gap_residual"] != counts["k1_hit"] + counts["non_k1"]:
        raise AssertionError("k=1 partition was inconsistent")
    result: dict[str, object] = {
        "arithmetic": (
            "exact SPF factorization, complete k=1 p-1 divisor scan, and "
            "unbounded-first-scale shared-divisor scan through the gap cap"
        ),
        "scope_note": (
            "This is a finite residual funnel. k>1 witnesses remain marked "
            "Type II representations rather than unmarked descent steps."
        ),
        "prime_limit": limit,
        "gap_cap": gap_cap,
        "core_prime_count": core_prime_count,
        "counts": counts,
        "non_k1_scale_histogram": dict(sorted(scale_histogram.items())),
        "non_k1_records": non_k1_records,
    }
    if include_single_prime_profile:
        result["single_prime_shared_profile"] = single_prime_shared_profile(
            non_k1_records, gap_cap, spf
        )
    if include_subgroup_threshold_profile:
        result["subgroup_threshold_shared_profile"] = subgroup_threshold_shared_profile(
            non_k1_records, gap_cap, spf
        )
    if include_p_group_davenport_profile:
        result["p_group_davenport_shared_profile"] = p_group_davenport_shared_profile(
            non_k1_records, gap_cap, spf
        )
    if include_rank_two_davenport_profile:
        result["rank_two_davenport_shared_profile"] = rank_two_davenport_shared_profile(
            non_k1_records, gap_cap, spf
        )
    if include_totient_threshold_profile:
        result["totient_threshold_shared_profile"] = totient_threshold_shared_profile(
            non_k1_records, gap_cap, spf
        )
    if include_prime_power_profile:
        result["prime_power_shared_profile"] = prime_power_shared_profile(
            non_k1_records, gap_cap, spf
        )
    if include_support_profile:
        result["multi_prime_support_profile"] = multi_prime_support_profile(
            non_k1_records, gap_cap, spf
        )
    if include_factor_length_profile:
        result["minimum_factor_length_profile"] = minimum_factor_length_profile(
            non_k1_records, gap_cap, spf
        )
    return result


